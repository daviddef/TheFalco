#!/usr/bin/env python3
"""Pull this archive's surname family out of the Record Atlas catalogue.

The Atlas catalogue (data/surname-families.json, written only by
scripts/surname_variants.py) is the one place spellings live. A deployed site
cannot read a sibling repository, so this writes a GENERATED snapshot,
site/src/data/atlas-surname-falco.json, that name.astro renders. Do not edit
the snapshot; add the form to the catalogue, publish, and run this again:

    python3 tools/pull_surname_catalogue.py
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CAT = os.path.join(HERE, "..", "..", "Record Atlas", "data", "surname-families.json")
OUT = os.path.join(HERE, "..", "site", "src", "data", "atlas-surname-falco.json")
FAMILY = "falco"
ORDER = ["same", "attested", "rule", "lead", "case-by-case"]

fams = json.load(open(CAT, encoding="utf-8"))
fams = fams.get("families", fams)
fam = next(f for f in fams if f["id"] == FAMILY)
members = sorted(fam["members"], key=lambda m: (ORDER.index(m["status"]) if m["status"] in ORDER else 9, m["form"]))
out = {
    "note": "GENERATED by tools/pull_surname_catalogue.py from the Record Atlas surname catalogue. Do not edit.",
    "family": fam["name"],
    "members": [{"form": m["form"], "status": m["status"],
                 "what": "; ".join(e["what"] for e in m.get("evidence", []))} for m in members],
    "notSame": [{"form": n.get("form"), "why": n.get("why")} for n in fam.get("notSame", [])],
}
open(OUT, "w", encoding="utf-8").write(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
print(f"{len(out['members'])} forms, {len(out['notSame'])} not-same -> {os.path.relpath(OUT)}")
